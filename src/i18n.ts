/** Roman numerals, for Spanish centuries ("siglo XX"). */
function roman(n: number): string {
    let out = "";
    for (const [v, r] of [[10, "X"], [9, "IX"], [5, "V"], [4, "IV"], [1, "I"]] as const) for (; n >= v; n -= v) out += r;
    return out;
}

